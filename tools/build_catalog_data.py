def volume(name):
    m = re.search(r"V\s*(\d+)\s*м3", name) or re.search(r"-(\d+)м3", name)
    return int(m.group(1)) if m else None


def mm(value):
    return int(re.sub(r"\D", "", value)) if value else None


def series_rows(purpose, subcategory):
    """{объём: {L, W, H, вес, толщина, фото}} по данным карточек Satu."""
    out = {}
    for p in SRC:
        if p["purpose"] != purpose or p["subcategory"] != subcategory:
            continue
        v = volume(p["name"])
        if v is None:
            continue
        dims = p["attributes"].get("Габаритные размеры", {})
        main = {**p["attributes"].get("Основные атрибуты", {}), **p["attributes"].get("Основные", {})}
        row = {
            "v": v,
            "L": mm(dims.get("Длина")),
            "W": mm(dims.get("Ширина")),
            "H": mm(dims.get("Высота")),
            "weight": mm(main.get("Вес")),
            "thickness": mm(main.get("Толщина стенок")),
            "images": p["images"],
        }
        prev = out.get(v)
        # если объём встречается дважды, берём карточку с размерами и фото
        if not prev or (row["L"] and not prev["L"]) or len(row["images"]) > len(prev["images"]):
            out[v] = row
    return dict(sorted(out.items()))


