def prepare_images(series_slug, rows, limit=3):
    """Берёт фото клиента из карточек ряда, кладёт сжатые копии в site/assets/img/catalog."""
    IMG_OUT.mkdir(parents=True, exist_ok=True)
    urls, seen = [], set()
    for row in rows.values():
        for u in row["images"]:
            name = re.sub(r"[^\w.-]", "_", u.split("/")[-1].split("?")[0])
            if name in seen:
                continue
            seen.add(name)
            urls.append(name)
    out = []
    for i, name in enumerate(urls[:limit], 1):
        src = IMG_SRC / name
        if not src.exists():
            continue
        im = Image.open(src).convert("RGB")
        base = f"{series_slug}-{i}"
        for suffix, width in (("", 1100), ("-sm", 560)):
            w = min(width, im.width)
            copy = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
            copy.save(IMG_OUT / f"{base}{suffix}.webp", "WEBP", quality=80, method=6)
        out.append(base)
    return out


def main():
    series_out = {}
    for slug, s in SERIES.items():
        rows = s["rows"]
        series_out[slug] = {
            **{k: v for k, v in s.items() if k != "rows"},
            "slug": slug,
            "table": [{k: v for k, v in row.items() if k != "images"} for row in rows.values()],
            "images": prepare_images(slug, rows),
        }

    data = {"categories": []}
    for c in CATEGORIES:
        cat = {k: v for k, v in c.items() if k != "series"}
        cat["series"] = []
        for slug, models in c["series"]:
            s = dict(series_out[slug])
            s["models"] = [m for m in models if any(r["v"] == m for r in s["table"])]
            cat["series"].append(s)
        cat["products"] = sum(len(s["models"]) for s in cat["series"])
        data["categories"].append(cat)

    (ROOT / "content/catalog.json").write_text(json.dumps(data, ensure_ascii=False, indent=2))
    for c in data["categories"]:
        print(f'{c["title"]}: рядов {len(c["series"])}, страниц товаров {c["products"]}')
    print("итого товаров:", sum(c["products"] for c in data["categories"]))


if __name__ == "__main__":
    main()
